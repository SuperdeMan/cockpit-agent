"""「这句话是在对我说，还是播报 / 转述给别人听」——受话边界的确定性一维（唯一实现）。

## 它挡的是什么

端侧分类器是「关键词共现」的正向匹配：一句广播「欢迎收听今天的节目，本台记者为您报道新闻。」
命中 `新闻` + `听` → `media.play`，**0.97s 内就把媒体置成 playing**（2026-09-11 语音采纳真栈探针
首轮，trace `ba82484fa8c54b9a`）。说话人是车里的收音机、副驾的手机，或任何把这句念出来的人——
不是用户在下指令。云侧受话判定（Planner 一次调用）管不到这条确定性快路径：它在上云之前就执行了。

> 判据：这与「问句不许被执行成写操作」（`question_shape`）、「别做 X 不许被执行成 X」（`polarity`）
> 是同一族——都是**「识别到关键词」≠「用户指令」**多出来的一个维度，落点也是同一个：
> `classify_structured` 出口只盖写操作，查询照旧秒回。

## 判据是「语域」，不是「新闻词表」

播报 / 转述有它自己的封闭语域标记——**说话人在对听众说话**（本台 / 记者 / 欢迎收听 / 各位听众 /
为您播报 / 以上是 / 据报道…）。这些词一个都不是车控或媒体的领域对象（源码级断言钉在
`runtime/tests/test_reported_speech.py`），所以它不会退化成「凡是提到新闻就不播」：
「播放新闻」「我要听体育新闻」「来段新闻」一个都不碰。

它**不是**声学层的说话人识别：同一句「播放新闻」由乘客说出来，这里认不出——那是 AR07 / 语音采纳
的声学问题，靠同条件声学证据，不靠文本。本模块只回答「这段**文本**的语域是不是在对听众播报」。

## 为什么住在 runtime/

端侧 `orchestrator/edge/fast_intent.py` 是第一个消费方；云侧镜像够不着 `orchestrator/edge`
（`orchestrator/cloud/Dockerfile` 只 COPY cloud/security/observability/runtime/skills），
而端侧镜像 COPY 了 `runtime`。同 `polarity.py` / `question_shape.py` 两次的落点判据：镜像依赖闭包。
"""
from __future__ import annotations

#: 播报 / 转述语域标记：说话人在对**听众**说话，不是在对助手下指令。全部是封闭的语域框架词，
#: **零领域词**（源码级断言守着）。刻意不收「他说 / 她说」——「我妈说让我把车窗关上」是用户在转达
#: 指令，挡它等于反向漏执行；也不收单独的「记者」——「播放记者会直播」是正常指令。
BROADCAST_FRAMES = (
    # 播出方自称
    "本台", "本节目", "本栏目", "本频道", "播音员", "主持人", "通讯员",
    "本台记者", "记者为", "记者报道", "记者了解", "记者获悉", "记者从",
    # 面向听众的招呼与收尾
    "欢迎收听", "欢迎收看", "感谢收听", "感谢收看", "欢迎回来", "欢迎来到",
    "各位听众", "各位观众", "听众朋友", "观众朋友", "各位朋友", "各位乘客",
    "以上是", "以上就是", "下面请听", "下面请看", "接下来请", "接下来为",
    # 「为您 / 为大家」是播报者或助手的口吻，用户对助手说话用的是「帮我 / 给我」
    "为您报道", "为您播报", "为您带来", "为您介绍", "为您播出", "为大家",
    # 转述框架
    "据报道", "据了解", "据悉", "消息称", "报道称", "通报称", "新华社",
)


def is_reported_speech(text: str) -> bool:
    """这段文本是不是在**对听众播报 / 转述**，而不是对助手说话。

    只回答语域，不回答「该做什么」——它是写操作的否决面：命中的句子整句上云，
    由云侧受话判定与 Planner 决定要不要回应；查询类结果不经这里。
    """
    t = (text or "").strip()
    if not t:
        return False
    return any(frame in t for frame in BROADCAST_FRAMES)
