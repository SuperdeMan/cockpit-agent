"""「就近」判据：原话在要**附近 / 离我最近的那一家**（跨服务唯一一份，零领域词）。

2026-10-17 demo-dqt1fu 复测：「帮我查一下我附近的麦当劳有什么可以点单的？」四次里三次被规划成一个空槽的 `mcd.menu`（没照范例先搜周边），
商户桥既没门店也没城市，只能退回账号收藏的门店（demo-3ukshz：「附近」答成十公里外的碧海君庭）或者让用户报门店和城市。原话里明明说了
「附近」——消费方拿这份判据决定「没给门店时改派周边按位置找」，而不是退回默认店。

只收**没有歧义**的说法：「最近」单用常是「近来」（「最近有什么新品」「最近的订单」），只有「离我（最）近」「最近（的）那家 / 一家 / 店」
这几种形状算「最近的那家」；宁可漏认（照旧走默认店 / 追问），不错认（把「最近出了什么新品」改派成周边搜索）。
"""
from __future__ import annotations

import re

_ASKS_NEARBY_RE = re.compile(
    r"附近|周边|就近|离我(?:最)?近|最近的?(?:那|一)?家|最近的?(?:门店|店)")


def asks_nearby(text) -> bool:
    """原话在要附近 / 最近的那一家 ⇒ True。"""
    return isinstance(text, str) and bool(_ASKS_NEARBY_RE.search(text))
