"""「这句话是不是一件待办」——`reminder.create` 侧的准入判据（C10-C，2026-08-28）。

## 它挡的是什么

写入闸此前只判 `fire_at > 0`（`store._prepare_new`）加两条否定守卫。于是
2026-08-26 长会话在库里留下两类**根本不是提醒**的条目，而且它们全都建成功了：

- **问句**：`刚才那个提醒现在几点` —— 用户在**问**，被建成了一条待办；
  更糟的是它随后进了序数参照系，T59 的「取消第一条」把它取消掉并报了这个标题。
- **第三人称事实陈述**：`用户计划2026年国庆…4天行程` —— 那是一条**记忆**，
  是别的域抽出来的事实句，不是这个人要做的事。

Q11 卡的③（任务性判据）当时只落了 offer 侧（`memory/offer_admission.py`
管「值不值得主动建议」），**create 侧一直没有对应物**。这份补上。

## 判据取形态，不取关键词

同 `offer_admission` 那条纪律：**没有按「查询/问了/搜了」这类词做排除**——
关键词排除换个转述就绕过去。这里判的是两个**句法形态**：

1. **疑问收尾**：剥掉语气尾（了/呀/啊/呢/吧/？）之后，句子**以疑问词结束**。
   ⚠ 刻意不判「句中有疑问词」：`问一下张总几点开会` 是一件真事，
   `几点` 在句中；`刚才那个提醒现在几点` 才是问句。**位置就是语义**
   （同 N9「词表分支序就是语义」的同一族判断）。
2. **第三人称主语开头**：`用户/该用户/客户/乘客` 打头。用户跟助手说话时说的是
   「我」，第三人称主语是**别的系统在描述他**——那是记忆的句式，不是待办的句式。

两条都只覆盖**观测到的那两类**，宁可漏不误杀：漏了顶多多一条垃圾提醒，
误杀的是用户真的要做的事。
"""
from __future__ import annotations

import re

#: 语气尾：判「以疑问词结尾」之前先剥掉，否则「现在几点了」躲过判据。
_TONE_TAIL_RE = re.compile(r"[了呀啊呢吧嘛\s。.！!？?]+$")

#: 疑问词（封闭类）。**只在剥完语气尾后判句尾**——见模块 docstring 第 1 条。
#: 末尾的 `吗|么` 是**是非问语气助词**：它在句尾只有一个意思，就是「这是个问句」。
#: ⚠ 它带一点误伤面（「问问他来吗」是一件真事），这条留着不放宽——那种说法
#: 本身就读作问句，而放宽它会把「明天下雨吗」这一族整个放回来（同 offer 侧
#: I-014 那个形态：一句天气查询被抽成了一条待办）。
_QUESTION_TAIL_RE = re.compile(
    r"(?:几点|几时|几号|多少钱|多少|多久|什么时候|"
    r"什么|啥|哪儿|哪里|哪天|哪条|哪个|哪些|怎么样|如何|"
    r"是不是|对不对|有没有|吗|么)$")

#: 第三人称主语开头 —— 这是「别的系统在描述这个人」的句式，不是待办的句式。
_THIRD_PERSON_RE = re.compile(r"^(?:该)?(?:用户|客户|乘客|车主)(?![:：]?$)")


def admit_task_title(title: str) -> tuple[bool, str]:
    """→ (能不能建?, 拒绝理由)。理由给日志和话术用，**不含关键词清单**。

    空标题不在本判据的职责内（调用方另有 NEED_SLOT 追问那条路），一律放行。
    """
    text = str(title or "").strip()
    if not text:
        return True, ""
    if _THIRD_PERSON_RE.match(text):
        return False, "第三人称陈述句是一条事实记录，不是这个人要做的事"
    stripped = _TONE_TAIL_RE.sub("", text)
    if stripped and _QUESTION_TAIL_RE.search(stripped):
        return False, "以疑问词收尾，这是在问一件事而不是要做一件事"
    return True, ""
