"""Infrastructure approval: move the release anchor to a reviewed commit.

The anchor /opt/car-agent/shared/release-infrastructure.json binds the host to one reviewed
commit's deploy/cloud/** (aggregate of per-file blob digests) and records which of those files
are installed where. A deploy only reads it (deploy/cloud/README.md). Approving a commit
installs its changed files and rewrites the anchor, as root, under the release transaction
lock, with a backup and an automatic restore on failure.

Eight approvals (2026-09-06..09-28) were generated by session-local scripts that lived only
under .artifacts/infrastructure-approval/; this module replaces them. The three root scripts
below are those scripts with their constants turned into placeholders.

- prepare_approval(): reads the installed anchor, builds the candidate from committed blobs of
  the target commit (REQUIRED_INSTALLED is read from that commit too), renders the materials
  into <artifact_root>/<sha>/ and runs the anchor validator locally. Changes nothing remotely.
- apply_approval(): re-reads the anchor (it must be the one the materials were built against),
  stages the materials through prepare-upload + scp, runs the digest-pinned root entry over
  `ssh sudo -n bash -s` and reads the anchor back.
"""

