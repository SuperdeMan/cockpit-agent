"""指令极性——「这句话是在让我**别做**某件事」（QA 卡 Q7）。

## 它要挡的是什么

端侧分类器是「对象 × 动作」的**正向、无序、无上下文**匹配：「车窗别开」切出来就是
对象词 `车窗` + 动作词 `开`，命中正向规则 → `window.open`，**「别」不是任何判据的
输入**。于是用户说「别开」，车窗开了（I-039）。同族：「空调别关」→ `hvac.off`。

> 判据：这不是「再多几条规则」能治的，**是多一个维度**。规则再多也只是在
> 「对象 × 动作」这个二维平面里挪位置。

## 为什么是「不执行」而不是「执行反向动作」

「车窗别开」的反向是 `window.close`——**用户没让你关**，他让你别开。
把「别开」映射成「关」只是换了一个错误动作，而且是一个**有副作用**的错误动作。
所以负极性的写操作在端侧一律**不产出本地意图**，整句交云端如实处理
（卡里那句「宁可慢一点，不要按反」）。

## 例外面：三类不是「别做这件事」

1. **「别忘了…」**——双重否定，真实语义是**要做**。挡它会造成反向漏执行。
2. **「不用了/算了」**——那是**取消挂起**，归 `pending_cancel`（Q1-A 已收敛的
   另一件事）。这里认了会和取消判定打架。
3. **否定词离动作太远**——「别催我，把空调打开」里的「别」否定的是「催」不是「打开」。
   判据要求否定词与动作词**紧邻**（≤6 字），同 Q4 位置闸那条邻接判据的形态。

⚠ **本模块是极性判据的唯一实现**。卡 §3-Q11 明写提醒的否定守卫（「别建提醒」）
与本判据同源，**共用一份，别写第二份**——「同一件事有两份实现，迟早有一份是错的」
这一批已经应验过两次（Q1-A 的取消词表、Q13 的意图命名）。
"""
from __future__ import annotations

import re

#: 否定词。刻意**不含**「不用/算了」——那是取消挂起（`pending_cancel`），不是「别做」。
_NEG = r"(?:别|甭|不要|不许|不准|勿|莫)"
#: 例外：双重否定，真实语义是**要做**。必须早于否定判据求值。
_DOUBLE_NEGATIVE_RE = re.compile(rf"{_NEG}\s*(?:忘|忘了|忘记)")
#: 否定词 + （最多 6 字间隔）+ 动作词。邻接是刻意的：
#: 「别催我，把空调打开」里的「别」否定的是「催」。间隔里不许跨标点。
_NEGATED_DIRECTIVE_RE = re.compile(
    rf"{_NEG}[^，。；！？,;!?]{{0,6}}?"
    r"(?:开|关|打开|关闭|开启|关掉|停|暂停|播放|放|调|设|升|降|锁|解锁|"
    r"折叠|展开|收起|打|启动|切换|静音)")


def is_negated_directive(text: str) -> bool:
    """这句话是不是「别做某个动作」。

    只回答极性，不回答「该做什么」——**后者没有正确答案**：
    「别开」的反面不是「关」，是「什么都不做」。
    """
    t = str(text or "").strip()
    if not t:
        return False
    if _DOUBLE_NEGATIVE_RE.search(t):
        return False
    return bool(_NEGATED_DIRECTIVE_RE.search(t))
