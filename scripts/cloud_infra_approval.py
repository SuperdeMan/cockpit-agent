SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
NONCE_RE = re.compile(r"^[0-9a-f]{32}$")
ANCHOR_KEYS = frozenset({"schema_version", "infrastructure_sha256", "source_files", "installed_files"})


class ApprovalError(RuntimeError):
    """An approval step refused or failed; the message says how far it got."""


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _canonical(source_files: Mapping[str, str]) -> bytes:
    return json.dumps(source_files, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def _strict_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ApprovalError("anchor has a duplicate key")
        result[key] = value
    return result


def parse_anchor(data: bytes) -> dict[str, Any]:
    try:
        payload = json.loads(data.decode("utf-8"), object_pairs_hook=_strict_object)
    except (UnicodeDecodeError, ValueError) as exc:
        raise ApprovalError("anchor is not valid JSON") from exc
    if not isinstance(payload, dict) or set(payload) != ANCHOR_KEYS or payload["schema_version"] != 1:
        raise ApprovalError("anchor shape is invalid")
    sources = payload["source_files"]
    if not isinstance(sources, dict) or any(
        not isinstance(value, str) or not SHA256_RE.fullmatch(value) for value in sources.values()
    ):
        raise ApprovalError("anchor source digests are invalid")
    if _sha256(_canonical(sources)) != payload["infrastructure_sha256"]:
        raise ApprovalError("anchor aggregate does not match its source digests")
    rows = payload["installed_files"]
    if not isinstance(rows, list) or any(
        not isinstance(row, dict) or set(row) != {"source_path", "target_path", "sha256"} for row in rows
    ):
        raise ApprovalError("anchor installed files are invalid")
    return payload


def read_anchor(request: ReleaseRequest, runner: CommandRunner) -> tuple[bytes, dict[str, Any]]:
    result = runner.run(
        request.ssh.ssh_argv(f"sudo -n cat {ANCHOR_PATH}"), cwd=request.repo, check=False, timeout_s=60
    )
    if result.returncode != 0:
        raise ApprovalError("could not read the installed infrastructure anchor")
    data = result.stdout.encode("utf-8")
    return data, parse_anchor(data)


# ---------------------------------------------------------------- candidate


def required_installed_at(repo: Path, sha: str) -> dict[str, str]:
    """REQUIRED_INSTALLED as committed in the target's remote preflight, not the working tree's."""
    text = _git_blob(repo, sha, "scripts/cloud_release_lib.py").decode("utf-8")
    match = re.search(r"^REQUIRED_INSTALLED = (\{.*?^\})", text, re.M | re.S)
    if match is None:
        raise ApprovalError("the target commit declares no REQUIRED_INSTALLED")
    required = ast.literal_eval(match.group(1))
    if not isinstance(required, dict) or any(
        not isinstance(source, str) or not source.startswith("deploy/cloud/")
        or not isinstance(target, str) or not target.startswith("/")
        for source, target in required.items()
    ):
        raise ApprovalError("REQUIRED_INSTALLED in the target commit is invalid")
    return required


@dataclass(frozen=True)
class Install:
    name: str
    source: str
    target: str
    mode: str
    new: str
    old: str  # "-" for a file the anchor did not install before


@dataclass(frozen=True)
class Candidate:
    target_sha: str
    aggregate: str
    source_files: dict[str, str]
    required: dict[str, str]
    anchor_bytes: bytes
    installs: tuple[Install, ...]
    blobs: dict[str, bytes]
    changed_sources: tuple[str, ...]


def build_candidate(repo: Path, target_sha: str, previous: Mapping[str, Any]) -> Candidate:
    listing = _git(repo, "ls-tree", "-r", "--name-only", target_sha, "--", "deploy/cloud").stdout.splitlines()
    paths = sorted(path for path in listing if path and path != "deploy/cloud/README.md")
    blobs = {path: _git_blob(repo, target_sha, path) for path in paths}
    sources = {path: _sha256(blobs[path]) for path in paths}
    aggregate = _sha256(_canonical(sources))
    if aggregate != compute_infrastructure_digest(repo, target_sha):
        raise ApprovalError("candidate aggregate disagrees with the release gate")
    required = required_installed_at(repo, target_sha)
    if set(required) - set(sources):
        raise ApprovalError("REQUIRED_INSTALLED names files outside deploy/cloud: "
                            + ", ".join(sorted(set(required) - set(sources))))
    previous_target = {row["source_path"]: row["target_path"] for row in previous["installed_files"]}
    previous_digest = {row["source_path"]: row["sha256"] for row in previous["installed_files"]}
    if set(previous_target) - set(required):
        raise ApprovalError("removing installed files is not supported: "
                            + ", ".join(sorted(set(previous_target) - set(required))))
    moved = sorted(source for source in required if previous_target.get(source, required[source]) != required[source])
    if moved:
        raise ApprovalError("moving installed files is not supported: " + ", ".join(moved))
    if LOCK_HELPER not in previous_digest or sources.get(LOCK_HELPER) != previous_digest[LOCK_HELPER]:
        raise ApprovalError("transaction-lock.sh must be installed and unchanged: the approval sources it")
    installs = []
    for source, target in required.items():
        if previous_digest.get(source) == sources[source]:
            continue
        name = source.rsplit("/", 1)[1]
        installs.append(Install(
            name=name,
            source=source,
            target=target,
            mode="0644" if name.endswith(CONFIG_SUFFIXES) else "0755",
            new=sources[source],
            old=previous_digest.get(source, "-"),
        ))
    names = [item.name for item in installs]
    if len(set(names)) != len(names) or set(names) & {APPLY, ANCHOR, WRAPPER, ENTRY}:
        raise ApprovalError("installed file names collide in the upload directory")
    anchor = {
        "infrastructure_sha256": aggregate,
        "installed_files": [
            {"sha256": sources[source], "source_path": source, "target_path": target}
            for source, target in required.items()
        ],
        "schema_version": 1,
        "source_files": sources,
    }
    before = previous["source_files"]
    return Candidate(
        target_sha=target_sha,
        aggregate=aggregate,
        source_files=sources,
        required=required,
        anchor_bytes=(json.dumps(anchor, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8"),
        installs=tuple(installs),
        blobs={item.name: blobs[item.source] for item in installs},
        changed_sources=tuple(sorted(p for p in set(sources) | set(before) if before.get(p) != sources.get(p))),
    )


